  public.public_api_approvals(text, uuid, bigint, integer, text), public.webhook_deliveries_due(text, integer),
  public.webhook_delivery_record(text, uuid, text, integer, integer, timestamptz) from public;
grant execute on function public.connection_rotate_tokens(text, uuid, jsonb, timestamptz, timestamptz),
