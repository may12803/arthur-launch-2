#!/usr/bin/env node
// Generates supabase/loveleeday/20261005_11_connector_definitions_seed.sql from data/connectors/systems/*.json.
// Idempotent upsert keyed on connector_definitions.key. Values (including UNVERIFIED labels) are copied as-is.
// build_status is always 'catalog_only': a researched catalog entry, never an adapter that has run. The table
// check constraint forbids 'live'. Usage: node scripts/gen-connector-seed.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'data/connectors/systems');
const out = path.join(root, 'supabase/loveleeday/20261005_11_connector_definitions_seed.sql');

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (Array.isArray(a) && a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const accessGate = (ar = {}) => {
  if (ar.partner_program_required === true) return 'partner_program';
  if (ar.self_serve_dev_account === true) return 'self_serve';
  if (ar.self_serve_dev_account === false) return 'customer_credentials';
  return 'UNVERIFIED';
};

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const rows = files.map((f) => {
  const j = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const key = f.replace(/\.json$/, '');
  const ar = j.access_requirements || {};
  const scopes = Array.isArray(j.auth?.scopes_needed_read) ? j.auth.scopes_needed_read : [];
  const objects = Array.isArray(j.data_objects_to_pull) ? j.data_objects_to_pull : [];
  return `  (${[
    q(key), q(j.system), q(j.vendor), q(j.category), q(j.auth?.method), q(accessGate(ar)), q(j.recommended_path),
    q(ar.partner_program_name ?? null), `${q(JSON.stringify(j.sandbox ?? {}))}::jsonb`, arr(objects),
    q(j.incremental_sync ?? null), q(j.rate_limits ?? null), arr(scopes), q('catalog_only'), 'null', q(`data/connectors/systems/${f}`),
  ].join(', ')})`;
});

const sql = `-- GENERATED by scripts/gen-connector-seed.mjs from data/connectors/systems/*.json (${files.length} systems). Do not edit by hand.
-- Idempotent upsert. UNVERIFIED labels in the source research are copied verbatim. build_status is 'catalog_only' for every row:
-- a catalog entry is research, not a running connector (the table check forbids 'live').
insert into public.connector_definitions
  (key, name, vendor, category, auth_method, access_gate, recommended_path, partner_program, sandbox, objects,
   incremental_sync, rate_limits, scopes, build_status, logo, source_file)
values
${rows.join(',\n')}
on conflict (key) do update set
  name = excluded.name, vendor = excluded.vendor, category = excluded.category, auth_method = excluded.auth_method,
  access_gate = excluded.access_gate, recommended_path = excluded.recommended_path, partner_program = excluded.partner_program,
  sandbox = excluded.sandbox, objects = excluded.objects, incremental_sync = excluded.incremental_sync,
  rate_limits = excluded.rate_limits, scopes = excluded.scopes, logo = coalesce(excluded.logo, public.connector_definitions.logo),
  source_file = excluded.source_file,
  build_status = case when public.connector_definitions.build_status = 'catalog_only' then excluded.build_status
                      else public.connector_definitions.build_status end;
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== sql) { console.error('seed is stale: run node scripts/gen-connector-seed.mjs'); process.exit(2); }
  console.log(`seed up to date (${files.length} systems)`);
} else {
  fs.writeFileSync(out, sql);
  console.log(`wrote ${path.relative(root, out)} (${files.length} systems)`);
}
