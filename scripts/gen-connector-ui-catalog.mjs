#!/usr/bin/env node
// Projects data/connectors/systems/*.json into lib/client-portal/connector-catalog.generated.ts: the fields the
// client-portal catalog and connect screens need, with research-only markers ("UNVERIFIED ...") removed so no
// customer reads our working notes. Reconciled with lib/connectors/definitions.generated.ts at merge.
// Usage: node scripts/gen-connector-ui-catalog.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "data/connectors/systems");
const logoDir = path.join(root, "public/connectors/logos");
const logos = fs.readdirSync(logoDir).filter((f) => !f.endsWith(".md"));
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const OVERRIDES = {
  "dynamics-365-business-central": "businesscentral.svg",
  "dynamics-365-finance-operations": "microsoftdynamics365.svg",
  "csv-excel-upload": null,
  "sftp-drop": null,
  "blackbaud-raisers-edge-nxt": null, // the file on disk is the Black code-formatter icon, the wrong brand
  "google-bigquery": "googlebigquery.svg",
  "azure-synapse": "azuresynapse.png",
  "oracle-fusion-cloud-erp": "oraclefusioncloud.svg",
  "clio-manage": "cliomanage.png",
};

function clean(s, max = 320) {
  if (typeof s !== "string") return "";
  let t = s.replace(/\(?[^().;]*UNVERIFIED[^().;]*\)?;?/gi, "").replace(/\s{2,}/g, " ").replace(/\s+([.,;])/g, "$1").trim();
  if (t.length > max) {
    const cut = t.slice(0, max);
    const stop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("; "));
    t = (stop > 80 ? cut.slice(0, stop) : cut.replace(/\s+\S*$/, "")) + (stop > 80 ? "." : "...");
  }
  return t;
}

// Research notes become customer copy only when they read as a statement: strip stray leading punctuation, and drop
// anything that is really a note to ourselves ("none", "not found", "no primary source", "(possibly ...)").
function note(t) {
  const s = t.replace(/^[.\s(]+/, "").replace(/\)$/, "").trim();
  if (!s || /^(none|n\/a|not |no |likely|possibly)/i.test(s) || /(source|not found|not stated|possibly|can vary)/i.test(s)) return "";
  return s.charAt(0).toUpperCase() + s.slice(1);
}

const out = [];
const unmatched = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const key = file.replace(/\.json$/, "");
  const d = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
  let logo = key in OVERRIDES ? OVERRIDES[key] : null;
  if (!(key in OVERRIDES)) {
    const n = norm(d.system);
    logo = logos.find((f) => norm(f.replace(/\.[a-z]+$/, "")) === n) || logos.find((f) => norm(f.replace(/\.[a-z]+$/, "")) === norm(key)) || null;
  }
  if (!logo && !(key in OVERRIDES)) unmatched.push(d.system);
  const ar = d.access_requirements || {};
  const sandbox = d.sandbox?.available;
  out.push({
    key,
    name: d.system,
    vendor: d.vendor,
    category: d.category,
    authMethod: d.auth?.method ?? "none",
    recommendedPath: d.recommended_path,
    partnerRequired: ar.partner_program_required === true,
    partnerProgram: note(clean(ar.partner_program_name, 140)),
    selfServeDev: ar.self_serve_dev_account === true,
    customerAdmin: note(clean(ar.customer_admin_must_do, 420)),
    timeToApproval: note(clean(ar.time_to_approval, 120)),
    scopes: (d.auth?.scopes_needed_read || []).map((s) => clean(String(s).split(" (")[0], 90)).filter((s) => /^[A-Za-z][A-Za-z0-9:._\/ -]{1,70}$/.test(s)),
    objects: (d.data_objects_to_pull || []).map((s) => clean(String(s), 60)).filter(Boolean).slice(0, 14),
    incremental: ((t) => (/^[A-Z][A-Za-z]/.test(t) ? t : ""))(clean(d.incremental_sync, 200)),
    sandbox: sandbox === true ? true : sandbox === false ? false : null,
    logo: logo ? `/connectors/logos/${logo}` : null,
  });
}

const header = `// GENERATED by scripts/gen-connector-ui-catalog.mjs from data/connectors/systems/*.json. Do not edit by hand.
// ${out.length} systems.
export type CatalogSource = {
  key: string; name: string; vendor: string; category: string; authMethod: string; recommendedPath: string;
  partnerRequired: boolean; partnerProgram: string; selfServeDev: boolean; customerAdmin: string; timeToApproval: string;
  scopes: string[]; objects: string[]; incremental: string; sandbox: boolean | null; logo: string | null;
};
export const CATALOG_SOURCES: CatalogSource[] = `;
fs.writeFileSync(path.join(root, "lib/client-portal/connector-catalog.generated.ts"), header + JSON.stringify(out, null, 1) + ";\n");
console.log(`wrote ${out.length} systems; no logo for: ${unmatched.join(", ") || "none"}`);
