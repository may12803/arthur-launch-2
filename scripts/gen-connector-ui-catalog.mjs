#!/usr/bin/env node
// Emits lib/client-portal/connector-admin-steps.generated.ts: for each system, what the customer's administrator does
// and the typical vendor approval wait. lib/connectors/definitions.generated.ts does not carry these two fields, so the
// portal reads them from the researched data/connectors/systems/*.json. Research-only markers ("UNVERIFIED ...",
// "none", "not found") are dropped so no customer reads our working notes.
// Usage: node scripts/gen-connector-ui-catalog.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "data/connectors/systems");

function clean(s, max) {
  if (typeof s !== "string") return "";
  let t = s.replace(/\(?[^().;]*UNVERIFIED[^().;]*\)?;?/gi, "").replace(/\s{2,}/g, " ").replace(/\s+([.,;])/g, "$1").trim();
  if (t.length > max) {
    const cut = t.slice(0, max);
    const stop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("; "));
    t = (stop > 80 ? cut.slice(0, stop) : cut.replace(/\s+\S*$/, "")) + (stop > 80 ? "." : "...");
  }
  return t;
}
function note(t) {
  const s = t.replace(/^[.\s(]+/, "").replace(/\)$/, "").trim();
  if (!s || /^(none|n\/a|not |no |likely|possibly)/i.test(s) || /(source|not found|not stated|possibly|can vary)/i.test(s)) return "";
  return s.charAt(0).toUpperCase() + s.slice(1);
}

const out = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"));
  const ar = d.access_requirements || {};
  out[file.replace(/\.json$/, "")] = { admin: note(clean(ar.customer_admin_must_do, 420)), wait: note(clean(ar.time_to_approval, 120)) };
}
const body = `// GENERATED by scripts/gen-connector-ui-catalog.mjs from data/connectors/systems/*.json. Do not edit by hand.
export const ADMIN_STEPS: Record<string, { admin: string; wait: string }> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.join(root, "lib/client-portal/connector-admin-steps.generated.ts"), body);
console.log(`wrote ${Object.keys(out).length} systems`);
