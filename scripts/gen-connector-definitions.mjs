#!/usr/bin/env node
// Generates lib/connectors/definitions.generated.ts from data/connectors/systems/*.json.
// Vendor text is copied verbatim: UNVERIFIED markers are preserved and listed in `unverified`.
// build_status is derived here and is never 'live' (live comes only from probes).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sysDir = path.join(root, 'data/connectors/systems');
const { ADAPTERS } = await import(path.join(root, 'lib/connectors/adapters/registry.ts'));
const implemented = new Set(Object.keys(ADAPTERS));

// Daniel's partner-gated list (adds Clover and Xero tiers) on top of access_gate === 'partner/license'.
const PARTNER_GATED_EXTRA = new Set(['clover', 'xero']);

// Structured rate limits only where the vendor JSON states a number.
const RATE = {
  'quickbooks-online': { rps: 500 / 60, burst: 10 },
  hubspot: { rps: 11, burst: 11 },
  clover: { rps: 16, burst: 16 },
  buildium: { rps: 10, burst: 10 },
  stripe: { rps: 25, burst: 25 },
  mailchimp: { rps: 10, burst: 10 },
  acumatica: { rps: 50 / 60, burst: 5 },
};
const DEFAULT_RATE = { rps: 2, burst: 2, source: 'default_unverified' };

const AUTH_MAP = {
  oauth2_authcode: 'oauth2_authcode',
  oauth2_client_credentials: 'oauth2_client_credentials',
  api_key: 'api_key',
  basic: 'basic',
  service_account: 'service_account',
  key_pair: 'key_pair',
  none: 'none',
};
const AUTH_OVERRIDE = {
  'csv-excel-upload': ['upload'],
  'sftp-drop': ['sftp'],
  // Customer grants a cross-account role; we assume it with ExternalId (no stored customer keys).
  'amazon-s3': ['service_account'],
  netsuite: ['oauth2_authcode', 'oauth1_tba'],
  box: ['oauth2_authcode', 'jwt'],
};

const logoDir = path.join(root, 'public/connectors/logos');
const logos = fs.existsSync(logoDir) ? fs.readdirSync(logoDir) : [];
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
function findLogo(key) {
  const k = norm(key);
  const hit = logos.find((f) => norm(f.replace(/\.[a-z]+$/, '')) === k);
  return hit ? `/connectors/logos/${hit}` : '';
}

const scan = (v) => /UNVERIFIED/i.test(typeof v === 'string' ? v : JSON.stringify(v ?? ''));

const defs = [];
for (const file of fs.readdirSync(sysDir).filter((f) => f.endsWith('.json')).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(sysDir, file), 'utf8'));
  const key = file.replace(/\.json$/, '');
  const ar = j.access_requirements || {};
  const gate = ar.partner_program_required === true ? 'partner/license' : ar.self_serve_dev_account === true ? 'self-serve' : 'unverified';
  const mapped = AUTH_OVERRIDE[key] || [AUTH_MAP[j.auth.method]];
  if (!mapped[0]) throw new Error(`unmapped auth ${j.auth.method} for ${key}`);
  const partnerGated = gate === 'partner/license' || PARTNER_GATED_EXTRA.has(key);
  const build_status = implemented.has(key) ? 'implemented' : partnerGated ? 'sftp_csv_path' : 'planned';
  const rate = RATE[key] ? { ...RATE[key], source: 'documented' } : DEFAULT_RATE;
  const unverified = [];
  const fields = {
    api_base_url: j.api.base_url,
    token_lifetime: j.auth.token_lifetime,
    refresh: j.auth.refresh,
    rate_limits: j.rate_limits,
    incremental_sync: j.incremental_sync,
    partner_program: ar.partner_program_name,
    scopes: j.auth.scopes_needed_read,
    sandbox: j.sandbox,
    objects: j.data_objects_to_pull,
    time_to_approval: ar.time_to_approval,
    cost_to_us: ar.cost_to_us,
  };
  for (const [n, v] of Object.entries(fields)) if (scan(v)) unverified.push(n);
  if (scan(j.api.openapi_spec_url)) unverified.push('openapi_spec_url');
  defs.push({
    key,
    name: j.system,
    vendor: j.vendor,
    category: j.category,
    auth_method: mapped[0],
    auth_methods: mapped,
    access_gate: gate,
    recommended_path: j.recommended_path,
    partner_program: ar.partner_program_name || '',
    sandbox: { available: j.sandbox.available, how_to_get: j.sandbox.how_to_get || '' },
    objects: j.data_objects_to_pull,
    incremental_sync: String(j.incremental_sync),
    rate_limits: String(j.rate_limits),
    rate_limit: rate,
    scopes: j.auth.scopes_needed_read || [],
    build_status,
    logo: findLogo(key),
    source_file: `data/connectors/systems/${file}`,
    api_base_url: j.api.base_url,
    token_lifetime: j.auth.token_lifetime || '',
    refresh: j.auth.refresh || '',
    build_effort_days: j.build_effort_days,
    blockers: j.blockers || [],
    unverified,
  });
}

const out = `// GENERATED by scripts/gen-connector-definitions.mjs from data/connectors/systems/*.json. Do not edit.
// UNVERIFIED markers in vendor text are preserved verbatim; \`unverified\` lists the fields that carry them.
import type { ConnectorDefinition } from './types.ts';

export const CONNECTOR_DEFINITIONS: ConnectorDefinition[] = ${JSON.stringify(defs, null, 2)};
`;
fs.writeFileSync(path.join(root, 'lib/connectors/definitions.generated.ts'), out);
const by = defs.reduce((a, d) => ((a[d.build_status] = (a[d.build_status] || 0) + 1), a), {});
console.log(`wrote ${defs.length} definitions`, by);
